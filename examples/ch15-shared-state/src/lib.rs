//! 第 15 章：共享可变状态的所有权设计
//!
//! 证据生成：tools/evidence.sh ch15-shared-state
//!
//! 本章的核心：**`Arc<Mutex<T>>` 不是唯一的答案，甚至常常不是最好的答案。**
//! 共享可变状态有四种典型设计，它们的**代价从零到"两条指令 + 分支"**：
//!
//! | 设计 | 谁在改 | 代价 | 什么时候用 |
//! |---|---|---|---|
//! | 独占所有权（move） | 只有一个所有者 | **零** | 数据是"一次性"的 |
//! | `Arc<T>`（只读共享） | 没人改 | 一次 `ldadd` | 读多写无 |
//! | `Arc<Mutex<T>>` | 谁都可能改 | `ldadd` + 锁 | 真的需要共享可变 |
//! | 分片 / 每线程一份 | 各改各的 | 零（最后合并） | 可并行归约 |
//!
//! ★ 结论先行：**`Arc<Mutex<T>>` 是"最后手段"，不是"默认选择"。**
//! 第 14 章说过"通过通信共享内存"—— 本章要说：
//! **能用所有权表达的，就不要用锁表达。**

use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Arc, Mutex};

// ============================================================
// 设计 1：独占所有权（move）—— 代价为零
// ============================================================

/// 数据被 **move** 进闭包，线程独占它。
///
/// ★ 这是第 14 章"发送即 move"的直接应用：
/// **没有任何共享**，所以不需要任何同步原语。
/// 汇编里就是普通的循环 —— 没有 `ldadd`、没有锁、没有屏障。
#[unsafe(no_mangle)]
pub fn owned_sum(v: Vec<u64>) -> u64 {
    let h = std::thread::spawn(move || v.iter().fold(0u64, |a, b| a.wrapping_add(*b)));
    h.join().unwrap()
}

// ============================================================
// 设计 2：`Arc<T>` 只读共享 —— 一次原子加
// ============================================================

/// 数据只读共享：`Arc<Vec<u64>>` 被 clone 给多个线程，**没人改**。
///
/// ★ 代价是每个 clone 一次 `ldadd`（第 13 章）。
/// 但**没有锁** —— 因为只读意味着"多线程同时访问"是安全的。
///
/// ★ 这里体现了 `Arc<T>: Send + Sync` 的条件（第 12 章）：
/// `T = Vec<u64>` 本身是 `Send + Sync`，所以 `Arc<Vec<u64>>` 也是。
#[unsafe(no_mangle)]
pub fn shared_read_sum(v: Arc<Vec<u64>>) -> u64 {
    let v2 = Arc::clone(&v);
    let h = std::thread::spawn(move || v2.iter().fold(0u64, |a, b| a.wrapping_add(*b)));
    let r = h.join().unwrap();
    // 本地还能继续用 v（引用计数 +1，不是 move）
    r + v.len() as u64
}

// ============================================================
// 设计 3：`Arc<Mutex<T>>` —— 真正需要共享可变时
// ============================================================

/// 多个线程往同一个累加器里写。
///
/// ★ 这是"共享可变状态"的标准写法，也是**最贵**的：
/// `ldadd`（Arc）+ `lock`/`unlock`（Mutex）+ 可能的 panic 路径
/// （`PoisonError`）+ 异常安全代码。
#[unsafe(no_mangle)]
pub fn mutex_accumulate(a: Arc<Mutex<u64>>, n: u64) -> u64 {
    for _ in 0..n {
        let mut g = a.lock().unwrap();
        *g = g.wrapping_add(1);
    }
    *a.lock().unwrap()
}

// ============================================================
// 设计 3'：同样的需求，用 atomic 就够了 —— 代价小得多
// ============================================================

/// 如果共享的状态只是一个**整数**，那么 `AtomicU64` 就够了 ——
/// 不需要锁，也不需要 `Arc`（`AtomicU64` 本身就能放进 `Arc` 里共享）。
///
/// ★ 这是本章最重要的一条实用建议：
/// **先问"共享的是什么"，再问"要不要锁"。**
/// 计数器、标志位、指针 —— 这些都有原子类型，**不需要 `Mutex`**。
#[unsafe(no_mangle)]
pub fn atomic_accumulate(a: Arc<AtomicU64>, n: u64) -> u64 {
    for _ in 0..n {
        a.fetch_add(1, Ordering::Relaxed);
    }
    a.load(Ordering::Relaxed)
}

// ============================================================
// 设计 4：每线程一份 —— 零共享
// ============================================================

/// 每个线程处理自己的一段，最后合并。
///
/// ★ 这是**并行归约**（map-reduce）的形状：
/// 线程内部**完全没有同步**，只在最后做一次加法。
/// 代价：`thread::scope` 的创建开销 + 最后那次合并。
#[unsafe(no_mangle)]
pub fn chunked_sum(v: &[u64]) -> u64 {
    let n = std::thread::available_parallelism().map(|n| n.get()).unwrap_or(1);
    let chunk = v.len().div_ceil(n).max(1);
    std::thread::scope(|s| {
        let handles: Vec<_> = v
            .chunks(chunk)
            .map(|c| s.spawn(move || c.iter().fold(0u64, |a, b| a.wrapping_add(*b))))
            .collect();
        handles.into_iter().map(|h| h.join().unwrap()).fold(0u64, u64::wrapping_add)
    })
}

// ============================================================
// 反例：`Rc<RefCell<T>>` 不能跨线程
// ============================================================

/// ★ 单线程里 `Rc<RefCell<T>>` 是"共享可变"的标准写法；
/// 但把它搬到多线程**立刻报错**（见 `fail/rc_refcell_thread.rs`）：
/// `Rc` 不是 `Send`，`RefCell` 不是 `Sync`。
///
/// **这不是"`Rc<RefCell>` 不好"，而是"它的设计目标就是单线程"。**
/// 搬到多线程的等价物是 `Arc<Mutex<T>>` —— 但代价完全不同：
///
/// | | `Rc<RefCell<T>>` | `Arc<Mutex<T>>` |
/// |---|---|---|
/// | 引用计数 | 普通加减（1 条 `add`） | 原子加（`ldadd`） |
/// | 借用检查 | **运行时**计数（panic 路径） | 阻塞等待 |
/// | 能跨线程 | ❌ | ✅ |
///
/// ★ 注意"借用检查"那一行：`RefCell` 在**运行时**检查借用规则，
/// 违反时 panic；而 `Mutex` 是**阻塞等待**。
/// 两者都会在汇编里留下代码 —— 见 `examples/ch05-project-tree` 的实测。
#[unsafe(no_mangle)]
pub fn local_refcell(r: &std::cell::RefCell<u64>) -> u64 {
    let mut b = r.borrow_mut();
    *b = b.wrapping_add(1);
    *b
}

// ============================================================
// 一个实用的判据表（本章的结论）
// ============================================================

/// 用类型表达"谁能改"的四个层次：
///
/// ```text
/// 1. T                → 独占：谁持有谁能改，编译器保证唯一
/// 2. Arc<T>           → 只读共享：谁都不能改
/// 3. Arc<AtomicU64>   → 共享可变，但只有"一个值"可改
/// 4. Arc<Mutex<T>>    → 共享可变，任意状态可改（最后手段）
/// ```
///
/// ★ 每一次"升级"都在**放宽约束**（能做更多事），
/// 同时**付出代价**（更多的同步指令）。
/// **设计的目标是"用最紧的约束满足需求"，而不是"直接用最灵活的"。**
///
/// ★ 还有一个不在表里但常常最好的选项：
///
/// ```text
/// 0. move            → 不共享：把数据交给需要它的那个线程
/// ```
///
/// 第 14 章的 channel 就是这个思路。**"不共享"永远是最便宜的方案。**
#[unsafe(no_mangle)]
pub fn exclusive_demo(v: Vec<u64>) -> u64 {
    // 独占：直接改，不需要任何同步
    let mut v = v;
    v.push(1);
    v.iter().fold(0u64, |a, b| a.wrapping_add(*b))
}
